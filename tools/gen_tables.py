"""Precompute CYBERDECK's lookup tables (the chip has no FPU): firmware/src/tables.h.
   python3 tools/gen_tables.py"""
import math
from pathlib import Path

FS = 44100.0
TICK = 16                      # control rate: one tick per 16 frames
TICK_HZ = FS / TICK


def tbl(name, vals, ctype="uint32_t"):
    rows = []
    for i in range(0, len(vals), 8):
        rows.append("    " + ", ".join(f"{v}u" for v in vals[i:i + 8]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(rows) + "\n};\n"


# filter: cutoff index 0..255 -> g = tan(pi fc / fs) in Q16, fc 20 Hz .. 18 kHz exponential
cut_g = []
for i in range(256):
    fc = 20.0 * (18000.0 / 20.0) ** (i / 255.0)
    cut_g.append(round(math.tan(math.pi * fc / FS) * 65536))

# envelope time 0..127 -> 1 ms .. 8 s (time to ~98 %), per-tick coefficient Q24: 1 - exp(-TICK / (tau fs))
rate16 = []
for p in range(128):
    t = 0.001 * 8000.0 ** (p / 127.0)
    tau = t / 4.0
    rate16.append(max(1, round((1.0 - math.exp(-TICK / (tau * FS))) * (1 << 24))))

# LFO rate 0..127 -> 0.05 .. 30 Hz: phase increment per control tick (32-bit phase)
lfo_inc = []
for p in range(128):
    f = 0.05 * 600.0 ** (p / 127.0)
    lfo_inc.append(round(f / TICK_HZ * 2 ** 32))

# glide 0..127 -> instant .. ~8 s, per control tick Q16 (1.0 = 65536 means instant)
glide = [65536]
for p in range(1, 128):
    t = 0.004 * 2000.0 ** (p / 127.0)
    glide.append(max(1, round((1.0 - math.exp(-1.0 / (t / 3.0 * TICK_HZ))) * 65536)))

out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* generated by tools/gen_tables.py: do not edit */",
       tbl("CUT_G", cut_g), tbl("RATE16", rate16), tbl("LFO_INC", lfo_inc), tbl("GLIDE_R", glide)]
dst = Path(__file__).resolve().parent.parent / "firmware" / "src" / "tables.h"
dst.write_text("\n".join(out))
print("wrote", dst, f"(CUT_G {cut_g[0]}..{cut_g[-1]}, RATE16 {rate16[0]}..{rate16[-1]})")
