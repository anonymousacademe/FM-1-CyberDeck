r"""The scene plates: grayscale PNGs (made in EffectCraft: assets/art/plates.jsx) -> one C header of 8-bit fields,
   firmware/gen/art_plates.h. The firmware maps each value through a live neon palette (src/scenes.h).
   python tools\art2plate.py assets\art\plates firmware\gen\art_plates.h
   boot.png is 240 x 240, p0..p7.png are 120 x 120 (one per page: OSC FLT ENV LFO FX GLO ARP SEQ)."""
import sys
from pathlib import Path
from PIL import Image

src, dst = Path(sys.argv[1]), Path(sys.argv[2])
NAMES = [("boot", 240)] + [(f"p{i}", 120) for i in range(8)]


def arr(name, im):
    v = list(im.tobytes())
    rows = [",".join(str(x) for x in v[i:i + 32]) + "," for i in range(0, len(v), 32)]
    return f"static const uint8_t {name}[{len(v)}] = {{\n" + "\n".join(rows) + "\n};\n"


out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* generated by tools/art2plate.py from assets/art/plates/<name>.png (EffectCraft: assets/art/plates.jsx): do not edit */"]
total = 0
for n, side in NAMES:
    im = Image.open(src / f"{n}.png").convert("L")
    if im.size != (side, side):
        im = im.resize((side, side), Image.LANCZOS)
    out.append(arr("PLATE_" + n.upper(), im))
    total += side * side
dst.write_text("\n".join(out))
print(f"wrote {dst}: {len(NAMES)} plates, {total} B")
